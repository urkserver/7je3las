def write_html(result: ScanResult, engagement: Engagement, out: Path) -> Path:
    out = Path(out)
    counts = result.counts()
    e = html.escape
    parts: list[str] = []
    a = parts.append

    a("<!doctype html><html lang='en'><head><meta charset='utf-8'>")
    a("<meta name='viewport' content='width=device-width,initial-scale=1'>")
    a(f"<title>{TOOL_NAME} - Security Assessment</title><style>{CSS}</style></head><body><div class='wrap'>")

    a("<header>")
    a(f"<h1><span>{TOOL_NAME}</span> :: SECURITY ASSESSMENT</h1>")
    a(f"<div class='sub'>TARGET: {e(str(engagement.target))}</div>")
    a(f"<div class='sub'>OPERATOR: {e(engagement.operator or 'unspecified')}"
      f" &nbsp;|&nbsp; GENERATED: "
      f"{datetime.now(timezone.utc).isoformat(timespec='seconds')} UTC"
      f" &nbsp;|&nbsp; ENGINE v{__version__}</div>")
    score = result.risk_score()
    a(f"<div class='sub' style='margin-top:8px'>POSTURE: "
      f"<b style='color:var(--warn)'>{e(result.posture())}</b> "
      f"({score}/100)</div>")
    a("<div class='meter'><i style='width:%d%%'></i></div>" % max(2, score))
    a("</header>")

    a("<div class='grid'>")
    for sev, color in (("CRITICAL", "var(--crit)"), ("HIGH", "var(--high)"),
                       ("MEDIUM", "var(--med)"), ("LOW", "var(--low)"),
                       ("INFO", "var(--info)")):
        a("<div class='card'>")
        a(f"<div class='n' style='color:{color}'>{counts[sev]}</div>")
        a(f"<div class='l'>{sev}</div></div>")
    a("</div>")

    a("<h2>Scope &amp; Authorisation</h2>")
    a("<div class='ok'><b>Authorised:</b> "
      + (e(Engagement.attestation_text) if engagement.authorized
         else "no attestation recorded")
      + "</div>")
    if engagement.scope_notes:
        a(f"<div class='note'><b>Scope:</b> {e(engagement.scope_notes)}</div>")
    a("<div class='note'><b>Method boundary:</b> passive and read-only. "
      "No process injection, memory manipulation, exploitation, credential "
      "attack or denial of service was performed. Findings derive from static "
      "analysis of files on disk and unauthenticated reads of the operator's "
      "own loopback endpoints. Evidence is redacted.</div>")

    inv = result.metadata.get("inventory", {})
    if inv:
        a("<h2>Target Inventory</h2><table>")
        a("<tr><th>Root</th><td><code>" + e(str(inv.get("root", ""))) + "</code></td></tr>")
        a(f"<tr><th>Files analysed</th><td>{inv.get('file_count', 0):,}</td></tr>")
        a(f"<tr><th>Total size</th><td>{inv.get('total_bytes', 0):,} bytes</td></tr>")
        if inv.get("by_extension"):
            top = ", ".join(f"{k} &times;{v}" for k, v in list(inv["by_extension"].items())[:12])
            a(f"<tr><th>Top extensions</th><td>{e(top)}</td></tr>")
        a("</table>")

    a(f"<h2>Findings ({len(result.findings)})</h2>")
    if not result.findings:
        a("<div class='ok'>No findings above the configured threshold.</div>")
    for cat, findings in result.by_category().items():
        a(f"<h3 style='color:var(--fg);font-size:13px;letter-spacing:1px'>"
          f"{e(cat)} &mdash; {len(findings)}</h3>")
        for f in findings:
            a("<details><summary>")
            a(f"<span class='sev {f.severity.label}'>{f.severity.label}</span>")
            a(f"<span>{e(f.rule_id)}</span>")
            a(f"<span>{e(f.title)}</span>")
            a(f"<span class='loc'>{e(f.location)}</span>")
            a("</summary><div class='body'>")
            if f.cwe:
                a(f"<p><b>Weakness:</b> {e(f.cwe)} &nbsp; "
                  f"<b>Confidence:</b> {f.confidence.label}</p>")
            if f.evidence:
                a(f"<p><b>Evidence:</b></p><pre>{e(f.evidence)}</pre>")
            a(f"<p><b>Description.</b> {e(f.description)}</p>")
            a(f"<p><b>Impact.</b> {e(f.impact)}</p>")
            a(f"<p><b>Remediation.</b> {e(f.remediation)}</p>")
            if f.references:
                a("<p><b>References.</b><br>" +
                  "<br>".join(e(r) for r in f.references) + "</p>")
            if f.tags:
                a("<p>" + "".join(f"<span class='tag'>{e(t)}</span>"
                                  for t in f.tags) + "</p>")
            a("</div></details>")

    a("<footer>")
    a(f"{TOOL_NAME} v{__version__} &mdash; authorized, read-only assessment. "
      "This document contains no exploit code and is safe to attach to a "
      "coordinated disclosure.</footer>")
    a("</div></body></html>")

    out.write_text("\n".join(parts), encoding="utf-8")
    return out


# --------------------------------------------------------------------------
# Facade
# --------------------------------------------------------------------------
def write_reports(result: ScanResult, engagement: Engagement,
                  outdir: Path, formats: list[str]) -> dict[str, Path]:
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    written: dict[str, Path] = {}
    if "json" in formats or "all" in formats:
        written["json"] = write_json(result, engagement, outdir / "fivem-audit.json")
    if "md" in formats or "all" in formats:
        written["md"] = write_markdown(result, engagement, outdir / "fivem-audit.md")
    if "html" in formats or "all" in formats:
        written["html"] = write_html(result, engagement, outdir / "fivem-audit.html")
    return written


# Attach the attestation text as a class attribute for reuse in templates.
Engagement.attestation_text = (
    "I confirm that I own this target or hold written authorization from its "
    "owner to perform a read-only security assessment, and that this scan is "
    "conducted within an agreed scope and window."
)
