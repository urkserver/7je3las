"""
Report generation: JSON (machine readable), Markdown (disclosure ready)
and a self-contained HTML briefing.

Reports describe *identified weaknesses with static evidence*. They are
written to be attached to a coordinated disclosure, and deliberately never
contain an exploit chain or runnable payload.
"""

from __future__ import annotations

import html
import json
from datetime import datetime, timezone
from pathlib import Path

from .core import Engagement, Finding, ScanResult, Severity, TOOL_NAME, __version__


# --------------------------------------------------------------------------
# JSON
# --------------------------------------------------------------------------
def write_json(result: ScanResult, engagement: Engagement, out: Path) -> Path:
    out = Path(out)
    payload = result.to_dict()
    payload["engagement"] = engagement.to_dict()
    payload["generated_utc"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    out.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    return out


# --------------------------------------------------------------------------
# Markdown - structured for a vulnerability disclosure submission
# --------------------------------------------------------------------------
def write_markdown(result: ScanResult, engagement: Engagement, out: Path) -> Path:
    out = Path(out)
    counts = result.counts()
    lines: list[str] = []
    a = lines.append

    a(f"# Security Assessment - {engagement.target}")
    a("")
    a(f"**Tool:** {TOOL_NAME} v{__version__}  ")
    a(f"**Generated:** {datetime.now(timezone.utc).isoformat(timespec='seconds')} UTC  ")
    a(f"**Operator:** {html.escape(engagement.operator) or 'unspecified'}  ")
    if engagement.ticket:
        a(f"**Reference / ticket:** {engagement.ticket}  ")
    a(f"**Overall posture:** {result.posture()} (risk score {result.risk_score()}/100)")
    a("")

    a("## 1. Scope and authorisation")
    a("")
    a("> " + (engagement.scope_notes or
              "Assessment of a locally installed Cfx.re / FiveM (FXServer) "
              "application tree owned or controlled by the operator."))
    a("")
    a("**Attestation of authorisation:**")
    a("")
    a("> " + (Engagement.attestation_text if engagement.authorized
              else "_No attestation recorded._"))
    a("")
    a("**Method boundary.** This assessment is strictly passive and read-only. "
      "No process injection, memory manipulation, code execution on a target, "
      "credential attack, denial-of-service, or exploitation of a third-party "
      "system was performed at any point. Findings are derived from static "
      "analysis of files on disk and from unauthenticated reads of the "
      "operator's own loopback endpoints.")
    a("")

    a("## 2. Summary")
    a("")
    a("| Severity | Count |")
    a("|---|---|")
    for sev in reversed(list(Severity)):
        a(f"| {sev.label} | {counts[sev.label]} |")
    a(f"| **Total** | **{len(result.findings)}** |")
    a("")

    inv = result.metadata.get("inventory", {})
    if inv:
        a("### Target inventory")
        a("")
        a(f"- Root: `{inv.get('root', 'n/a')}`")
        a(f"- Files analysed: {inv.get('file_count', 0):,}")
        a(f"- Total size: {inv.get('total_bytes', 0):,} bytes")
        if inv.get("by_extension"):
            top = ", ".join(f"{k} ({v})" for k, v in list(inv["by_extension"].items())[:10])
            a(f"- Most common extensions: {top}")
        a("")

    a("## 3. Findings")
    a("")
    if not result.findings:
        a("_No findings above the configured threshold._")
        a("")
    else:
        for cat, findings in result.by_category().items():
            a(f"### {cat}")
            a("")
            for f in findings:
                a(_md_finding(f))
    a("## 4. Recommended remediation order")
    a("")
    order = sorted(result.findings, key=lambda f: -int(f.severity))
    seen: set[str] = set()
    n = 0
    for f in order:
        if f.rule_id in seen:
            continue
        seen.add(f.rule_id)
        n += 1
        a(f"{n}. **[{f.severity.label}] {f.title}** - {f.remediation}")
    a("")
    a("---")
    a("")
    a("_Generated by " + TOOL_NAME + " v" + __version__ +
      ". Evidence values are redacted so this document can be shared safely._")

    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def _md_finding(f: Finding) -> str:
    loc = f.location
    parts = [
        f"#### {f.rule_id} - {f.title}",
        "",
        f"- **Severity:** {f.severity.label}",
        f"- **Category:** {f.category}",
        f"- **Confidence:** {f.confidence.label}",
    ]
    if f.cwe:
        parts.append(f"- **Weakness:** {f.cwe}")
    parts.append(f"- **Location:** `{loc}`")
    if f.evidence:
        parts.append(f"- **Evidence:** `{f.evidence}`")
    parts += [
        "",
        f"**Description.** {f.description}",
        "",
        f"**Impact.** {f.impact}",
        "",
        f"**Remediation.** {f.remediation}",
    ]
    if f.references:
        parts += ["", "**References.**"]
        parts += [f"- {r}" for r in f.references]
    if f.tags:
        parts += ["", f"*Tags: {', '.join(f.tags)}*"]
    parts += [""]
    return "\n".join(parts)


